// Writes supabase/setup.sql: everything a new Supabase project needs, in one file to paste
// into the SQL Editor once. Tables, RLS and policies come from the Drizzle migrations in
// drizzle/ (generated from lib/db/schema.ts); the Storage bucket from supabase/storage.sql.
// Run after `npm run db:generate`: `npm run db:setup-sql`.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const migrations = readdirSync("drizzle")
  .filter((name) => name.endsWith(".sql"))
  .sort()
  .map((name) => `-- ${name}\n${readFileSync(`drizzle/${name}`, "utf8").replaceAll("--> statement-breakpoint", "")}`);

const header = [
  "-- MockBuddy: database and storage setup for a new Supabase project.",
  "-- Paste this whole file into Supabase → SQL Editor → New query, and click Run, once.",
  "-- Generated by `npm run db:setup-sql`; edit lib/db/schema.ts or supabase/storage.sql instead.",
  "",
].join("\n");

writeFileSync("supabase/setup.sql", `${header}\n${migrations.join("\n")}\n-- supabase/storage.sql\n${readFileSync("supabase/storage.sql", "utf8")}`);
console.log("wrote supabase/setup.sql");
